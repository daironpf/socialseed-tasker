@issues_router.post(
    "/issues",
    response_model=APIResponse[IssueResponse],
    status_code=201,
    summary="Create a new issue",
    description=(
        "Create a new issue in the task management system. "
        "The issue will be linked to an existing component and can have "
        "labels and architectural constraints assigned."
    ),
    responses={
        201: {"description": "Issue created successfully"},
        404: {"description": "Component not found"},
        400: {"description": "Validation error"},
    },
)
def create_issue(
    body: IssueCreateRequest,
    repo: TaskRepositoryInterface = Depends(get_repo),
) -> APIResponse[IssueResponse]:
    """Create a new issue.

    Creates a new issue linked to a component. The issue title is validated
    and sanitized to prevent XSS attacks. Descriptions are also sanitized.

    Args:
        body: Issue creation request with title, description, priority, etc.
        repo: Repository dependency for data access.

    Returns:
        APIResponse with the created IssueResponse.

    Raises:
        HTTPException 400: If title validation fails.
        HTTPException 404: If the specified component doesn't exist.

    Example:
        ```bash
        curl -X POST /api/v1/issues \\
          -H "Content-Type: application/json" \\
          -d '{"title": "Fix auth bug", "priority": "HIGH", "component_id": "uuid-here"}'
        ```

        Response:
        ```json
        {
          "data": {
            "id": "uuid-here",
            "title": "Fix auth bug",
            "status": "todo",
            "priority": "HIGH",
            ...
          },
          "meta": {"timestamp": "...", "warnings": null}
        }
        ```
    """
    from fastapi import HTTPException

    from socialseed_tasker.domain import (
        IssueDescriptionValidationError,
        IssueTitleValidationError,
        sanitize_issue_description,
        sanitize_issue_title,
        validate_issue_title,
    )

    try:
        validated_title = validate_issue_title(body.title)
    except IssueTitleValidationError as e:
        raise HTTPException(status_code=400, detail=str(e))

    try:
        sanitized_description = sanitize_issue_description(body.description or "")
    except IssueDescriptionValidationError as e:
        raise HTTPException(status_code=400, detail=str(e))

    sanitized_title = sanitize_issue_title(validated_title)

    from socialseed_tasker.cli.wiring import build_default_container as _build_container
    from uuid import uuid4
    _dq_container = _build_container()
    _dq_pipeline = _dq_container.data_quality_pipeline
    _dq_record_id = str(uuid4())
    _dq_pre = _dq_pipeline.run_pre_ingest(body.model_dump(), record_id=_dq_record_id)
    if any(not r.ok for r in _dq_pre):
        from fastapi.responses import JSONResponse
        return JSONResponse(status_code=400, content={"status": "error", "error": "data_quality_failed", "details": [r.model_dump() for r in _dq_pre]})

    issue, warnings = create_issue_action(
        repo,
        title=sanitized_title,
        component_id=body.component_id,
        description=sanitized_description,
        priority=body.priority,
        labels=body.labels,
        architectural_constraints=body.architectural_constraints,
    )
    _dq_pipeline.run_post_ingest(body.model_dump(), record_id=str(issue.id))
    return APIResponse(
        data=_issue_to_response(issue), meta=Meta(request_id=None, warnings=warnings if warnings else None)
    )


@issues_router.post(
    "/issues/batch",
    response_model=APIResponse[BulkIssueCreateResponse],
    status_code=201,
    summary="Create multiple issues at once",
    description=(
        "Create multiple issues in a single request. "
        "Each issue is validated and created independently. "
        "The response reports per-item success/failure."
    ),
    responses={
        201: {"description": "Batch processed (check results for per-item status)"},
        400: {"description": "Validation error in request structure"},
    },
)
def create_issues_batch(
    body: BulkIssueCreateRequest,
    repo: TaskRepositoryInterface = Depends(get_repo),
) -> APIResponse[BulkIssueCreateResponse]:
    """Create multiple issues in a single request.

    Each issue is processed independently. The response includes
    per-item results with success/failure status for each issue.
    """
    if not body.issues:
        raise HTTPException(status_code=400, detail="No issues provided")

    from socialseed_tasker.domain import (
        IssueDescriptionValidationError,
        IssueTitleValidationError,
        sanitize_issue_description,
        sanitize_issue_title,
        validate_issue_title,
    )

    successful = 0
    failed = 0
    results: list[BulkIssueCreateResult] = []

    for idx, item in enumerate(body.issues):
        try:
            validated_title = validate_issue_title(item.title)
        except IssueTitleValidationError as e:
            failed += 1
            results.append(BulkIssueCreateResult(index=idx, status="error", title=item.title, error=str(e)))
            continue

        try:
            sanitized_description = sanitize_issue_description(item.description or "")
        except IssueDescriptionValidationError as e:
            failed += 1
            results.append(BulkIssueCreateResult(index=idx, status="error", title=item.title, error=str(e)))
            continue

        sanitized_title = sanitize_issue_title(validated_title)

        try:
            issue, warnings = create_issue_action(
                repo,
                title=sanitized_title,
                component_id=item.component_id,
                description=sanitized_description,
                priority=item.priority,
                labels=item.labels,
                architectural_constraints=item.architectural_constraints,
            )
            successful += 1
            results.append(
                BulkIssueCreateResult(
                    index=idx, status="created", issue_id=str(issue.id), title=sanitized_title
                )
            )
        except Exception as e:
            failed += 1
            results.append(BulkIssueCreateResult(index=idx, status="error", title=item.title, error=str(e)))

    return APIResponse(
        data=BulkIssueCreateResponse(
            total_requested=len(body.issues),
            successful=successful,
            failed=failed,
            results=results,
        ),
        meta=Meta(request_id=None),
    )


@issues_router.get(
    "/issues",
    response_model=APIResponse[list[IssueResponse]],
    summary="List issues",
    description=(
        "List issues with optional filters for status, component, and labels. "
        "Supports pagination via page and limit query parameters."
    ),
    operation_id="list_all_issues",
)
def list_issues(
    status: str | None = Query(None, description="Filter by status"),
    component: str | None = Query(None, description="Filter by component ID"),
    component_id: str | None = Query(None, description="Alias for component"),
    project: str | None = Query(None, description="Filter by project name"),
    title: str | None = Query(None, description="Filter by exact issue title"),
    page: int = Query(1, ge=1, description="Page number (starts at 1, default: 1)"),
    limit: int = Query(50, ge=1, le=100, description="Items per page (default: 50, max: 100)"),
    repo: TaskRepositoryInterface = Depends(get_repo),
):
    comp = component or component_id
    status_list = [s.strip() for s in status.split(",") if s.strip()] if status else []
    all_issues = repo.list_issues(component_id=comp, statuses=status_list, project=project)
    if title:
        all_issues = [i for i in all_issues if i.title == title]
    total = len(all_issues)
    start = (page - 1) * limit
    end = start + limit
    page_items = all_issues[start:end]

    return APIResponse(
        data=[_issue_to_response(i) for i in page_items],
        meta=Meta(
            request_id=None,
            pagination=PaginationMeta(
                page=page,
                limit=limit,
                total=total,
                has_next=(page * limit) < total,
                has_prev=page > 1,
            ),
        ),
    )


