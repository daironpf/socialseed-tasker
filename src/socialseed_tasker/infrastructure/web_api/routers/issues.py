@issues_router.post(
    "/issues/{issue_id}/close",
    response_model=APIResponse[IssueResponse],
    summary="Close an issue",
    description=("Close an issue. Fails if the issue has open dependencies or is already closed."),
    responses={
        404: {"description": "Issue not found"},
        409: {"description": "Already closed or has open dependencies"},
    },
)
def close_issue(
    issue_id: str,
    commit_sha: str | None = Body(None, description="Git commit SHA that resolved this issue"),
    resolution: str = Body("implemented", description="Resolution type: implemented, duplicate, wontfix, etc."),
    affected_files: list[str] = Body([], description="Files affected by this issue"),
    force: bool = Query(False, description="Force close even with policy violations"),
    repo: TaskRepositoryInterface = Depends(get_repo),
    request: Request = Depends(get_code_graph_driver),
):
    from socialseed_tasker.application.analyzer import ArchitecturalAnalyzer
    
    issue = repo.get_issue(issue_id)
    if issue is None:
        raise IssueNotFoundError(issue_id)
    
    if not force and issue.component_id:
        analyzer = ArchitecturalAnalyzer(repo)
        validation = analyzer.validate_issue_creation(issue)
        has_blocker = any(v.severity.value == "ERROR" for v in validation.violations)
        if has_blocker:
            from fastapi import HTTPException
            raise HTTPException(
                status_code=409,
                detail={
                    "error": "Policy violation - BLOCKER severity",
                    "violations": [
                        {"rule": v.rule_name, "message": v.message}
                        for v in validation.violations
                    ],
                    "hint": "Use ?force=true to override (not recommended)"
                }
            )
    
    issue = close_issue_action(repo, issue_id, commit_sha, resolution)

    if affected_files and request:
        try:
            if hasattr(request, 'driver'):
                driver = request.driver
            elif hasattr(request.app.state, 'driver'):
                driver = request.app.state.driver
                if hasattr(driver, 'driver'):
                    driver = driver.driver
            else:
                driver = None

            if driver:
                from socialseed_tasker.infrastructure.neo4j_code_graph_repository import CodeGraphRepository
                code_repo = CodeGraphRepository(driver)
                for file_path in affected_files:
                    code_repo.link_issue_to_file_with_symbols(issue_id, file_path)
        except Exception:
            pass

    return APIResponse(data=_issue_to_response(issue), meta=Meta(request_id=None))


